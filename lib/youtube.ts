// 유튜브 자막(대본)을 가져오는 모듈.
// 공식 API는 남의 영상 자막 다운로드를 허용하지 않아서, 유튜브 앱이 쓰는
// 내부(innertube) 플레이어 API로 자막 목록을 받아 옵니다.

const WATCH_URL = "https://www.youtube.com/watch?v=";
const PLAYER_URL = "https://www.youtube.com/youtubei/v1/player?key=";
const INNERTUBE_CONTEXT = {
  client: { clientName: "ANDROID", clientVersion: "20.10.38" },
};
const HEADERS = {
  "Accept-Language": "ko-KR,ko;q=0.9,en;q=0.8",
  "User-Agent":
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36",
};

export type Segment = { start: number; text: string };

export type Transcript = {
  videoId: string;
  title: string;
  channel: string;
  lengthSeconds: number;
  language: string;
  isAutoGenerated: boolean;
  segments: Segment[];
};

export class TranscriptError extends Error {
  constructor(
    public code:
      | "INVALID_URL"
      | "VIDEO_UNAVAILABLE"
      | "NO_CAPTIONS"
      | "BLOCKED"
      | "FETCH_FAILED",
    message: string,
  ) {
    super(message);
  }
}

type CaptionTrack = {
  baseUrl: string;
  languageCode: string;
  kind?: string;
  name?: { runs?: { text: string }[]; simpleText?: string };
};

export function parseVideoId(input: string): string | null {
  const trimmed = input.trim();
  if (/^[\w-]{11}$/.test(trimmed)) return trimmed;
  let url: URL;
  try {
    url = new URL(trimmed.startsWith("http") ? trimmed : `https://${trimmed}`);
  } catch {
    return null;
  }
  const host = url.hostname.replace(/^(www\.|m\.|music\.)/, "");
  let id: string | null = null;
  if (host === "youtu.be") {
    id = url.pathname.slice(1).split("/")[0];
  } else if (host === "youtube.com" || host === "youtube-nocookie.com") {
    if (url.pathname === "/watch") id = url.searchParams.get("v");
    else {
      const m = url.pathname.match(/^\/(shorts|embed|live|v)\/([\w-]{11})/);
      if (m) id = m[2];
    }
  }
  return id && /^[\w-]{11}$/.test(id) ? id : null;
}

async function fetchText(url: string, init?: RequestInit): Promise<string> {
  let res: Response;
  try {
    res = await fetch(url, { ...init, headers: { ...HEADERS, ...init?.headers } });
  } catch (e) {
    throw new TranscriptError("FETCH_FAILED", `유튜브에 연결하지 못했어요: ${(e as Error).message}`);
  }
  if (res.status === 429) {
    throw new TranscriptError("BLOCKED", "유튜브가 이 서버의 요청을 막았어요 (429).");
  }
  if (!res.ok) {
    throw new TranscriptError("FETCH_FAILED", `유튜브 응답 오류 (${res.status})`);
  }
  return res.text();
}

// 한국어 수동 자막 → 다른 수동 자막 → 한국어 자동 자막 → 아무 자동 자막 순으로 고릅니다.
function pickTrack(tracks: CaptionTrack[]): CaptionTrack {
  const manual = tracks.filter((t) => t.kind !== "asr");
  const auto = tracks.filter((t) => t.kind === "asr");
  return (
    manual.find((t) => t.languageCode.startsWith("ko")) ??
    manual.find((t) => t.languageCode.startsWith("en")) ??
    manual[0] ??
    auto.find((t) => t.languageCode.startsWith("ko")) ??
    auto[0]
  );
}

function decodeEntities(s: string): string {
  return s
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/<[^>]+>/g, "");
}

function parseCaptionXml(xml: string): Segment[] {
  const segments: Segment[] = [];
  const re = /<text start="([\d.]+)"[^>]*>([\s\S]*?)<\/text>/g;
  for (const m of xml.matchAll(re)) {
    const text = decodeEntities(decodeEntities(m[2])).replace(/\s+/g, " ").trim();
    if (text) segments.push({ start: Number(m[1]), text });
  }
  return segments;
}

// SUPADATA_API_KEY가 있으면 자막 전문 API(Supadata)를 쓰고, 없으면 유튜브에서 직접 가져옵니다.
// 서버(GitHub, 클라우드)에서는 유튜브가 직접 요청을 로봇으로 보고 막는 경우가 많아요.
export async function fetchTranscript(input: string): Promise<Transcript> {
  const videoId = parseVideoId(input);
  if (!videoId) {
    throw new TranscriptError("INVALID_URL", "유튜브 영상 링크를 확인해 주세요.");
  }
  if (process.env.SUPADATA_API_KEY) return fetchViaSupadata(videoId, process.env.SUPADATA_API_KEY);
  try {
    return await fetchDirect(videoId);
  } catch (e) {
    if (e instanceof TranscriptError && e.code === "BLOCKED") {
      e.message += " SUPADATA_API_KEY를 설정하면 자막 API로 우회할 수 있어요.";
    }
    throw e;
  }
}

const SUPADATA_URL = "https://api.supadata.ai/v1/transcript";

type SupadataTranscript = {
  content: { text: string; offset: number; duration: number }[];
  lang: string;
};

async function supadataGet(url: string, apiKey: string): Promise<{ status: number; body: any }> {
  let res: Response;
  try {
    res = await fetch(url, { headers: { "x-api-key": apiKey } });
  } catch (e) {
    throw new TranscriptError("FETCH_FAILED", `자막 API에 연결하지 못했어요: ${(e as Error).message}`);
  }
  const body = await res.json().catch(() => ({}));
  if (res.status === 206 || body.error === "transcript-unavailable") {
    throw new TranscriptError("NO_CAPTIONS", "이 영상에는 자막이 없어서 아직 요약할 수 없어요.");
  }
  if (res.status === 401 || res.status === 403) {
    throw new TranscriptError("FETCH_FAILED", "자막 API 키가 잘못됐어요. SUPADATA_API_KEY를 확인해 주세요.");
  }
  if (res.status === 429 || res.status === 402) {
    throw new TranscriptError("BLOCKED", "자막 API 사용 한도를 넘었어요.");
  }
  if (res.status === 404) {
    throw new TranscriptError("VIDEO_UNAVAILABLE", "영상을 찾을 수 없어요.");
  }
  if (!res.ok) {
    throw new TranscriptError("FETCH_FAILED", `자막 API 오류 (${res.status}): ${body.message ?? ""}`);
  }
  return { status: res.status, body };
}

async function fetchViaSupadata(videoId: string, apiKey: string): Promise<Transcript> {
  const query = new URLSearchParams({
    url: `https://www.youtube.com/watch?v=${videoId}`,
    lang: "ko",
    mode: "native",
  });
  let { status, body } = await supadataGet(`${SUPADATA_URL}?${query}`, apiKey);

  // 긴 영상은 작업 번호(jobId)를 먼저 주고, 완료될 때까지 기다려야 해요.
  if (status === 202 && body.jobId) {
    const jobUrl = `${SUPADATA_URL}/${body.jobId}`;
    for (let i = 0; i < 60; i++) {
      await new Promise((r) => setTimeout(r, 2000));
      ({ body } = await supadataGet(jobUrl, apiKey));
      if (body.status === "completed") break;
      if (body.status === "failed") {
        throw new TranscriptError("FETCH_FAILED", `자막 API 작업 실패: ${body.error?.message ?? ""}`);
      }
    }
    if (body.status !== "completed") {
      throw new TranscriptError("FETCH_FAILED", "자막 API 응답이 너무 오래 걸려요.");
    }
  }

  const data = body as SupadataTranscript;
  if (!Array.isArray(data.content) || data.content.length === 0) {
    throw new TranscriptError("NO_CAPTIONS", "자막 내용이 비어 있어요.");
  }
  const segments = data.content
    .map((c) => ({ start: c.offset / 1000, text: decodeEntities(c.text).replace(/\s+/g, " ").trim() }))
    .filter((s) => s.text);
  const last = data.content[data.content.length - 1];
  const meta = await fetchOEmbed(videoId);
  return {
    videoId,
    title: meta.title,
    channel: meta.channel,
    lengthSeconds: Math.round((last.offset + last.duration) / 1000),
    language: data.lang,
    isAutoGenerated: false,
    segments,
  };
}

// 제목과 채널명은 유튜브 oEmbed에서 가져와요. 실패해도 요약은 계속해요.
async function fetchOEmbed(videoId: string): Promise<{ title: string; channel: string }> {
  try {
    const res = await fetch(
      `https://www.youtube.com/oembed?format=json&url=${encodeURIComponent(`https://www.youtube.com/watch?v=${videoId}`)}`,
    );
    if (!res.ok) return { title: "", channel: "" };
    const j = await res.json();
    return { title: j.title ?? "", channel: j.author_name ?? "" };
  } catch {
    return { title: "", channel: "" };
  }
}

async function fetchDirect(videoId: string): Promise<Transcript> {
  const html = await fetchText(WATCH_URL + videoId, {
    headers: { Cookie: "CONSENT=YES+cb" },
  });
  if (html.includes('class="g-recaptcha"')) {
    throw new TranscriptError("BLOCKED", "유튜브가 이 서버에 로봇 확인을 요구하고 있어요.");
  }
  const apiKey = html.match(/"INNERTUBE_API_KEY":\s*"([\w-]+)"/)?.[1];
  if (!apiKey) {
    throw new TranscriptError("FETCH_FAILED", "유튜브 페이지 형식을 읽지 못했어요.");
  }

  const player = JSON.parse(
    await fetchText(PLAYER_URL + apiKey, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ context: INNERTUBE_CONTEXT, videoId }),
    }),
  );

  const status = player.playabilityStatus?.status;
  if (status && status !== "OK") {
    if (status === "LOGIN_REQUIRED" && /bot/i.test(player.playabilityStatus?.reason ?? "")) {
      throw new TranscriptError("BLOCKED", "유튜브가 이 서버를 로봇으로 판단해 막았어요.");
    }
    throw new TranscriptError(
      "VIDEO_UNAVAILABLE",
      `영상을 볼 수 없어요: ${player.playabilityStatus?.reason ?? status}`,
    );
  }

  const tracks: CaptionTrack[] =
    player.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
  if (tracks.length === 0) {
    throw new TranscriptError("NO_CAPTIONS", "이 영상에는 자막이 없어서 아직 요약할 수 없어요.");
  }

  const track = pickTrack(tracks);
  if (track.baseUrl.includes("&exp=xpe")) {
    throw new TranscriptError("BLOCKED", "유튜브가 추가 인증(PO 토큰)을 요구하고 있어요.");
  }
  const segments = parseCaptionXml(await fetchText(track.baseUrl.replace("&fmt=srv3", "")));
  if (segments.length === 0) {
    throw new TranscriptError("NO_CAPTIONS", "자막 내용이 비어 있어요.");
  }

  const details = player.videoDetails ?? {};
  return {
    videoId,
    title: details.title ?? "",
    channel: details.author ?? "",
    lengthSeconds: Number(details.lengthSeconds ?? 0),
    language: track.languageCode,
    isAutoGenerated: track.kind === "asr",
    segments,
  };
}
