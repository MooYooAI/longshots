import Anthropic from "@anthropic-ai/sdk";
import { zodOutputFormat } from "@anthropic-ai/sdk/helpers/zod";
import { z } from "zod";
import type { Transcript } from "./youtube";

// 기본 요약 모델. 기획서의 원가 계산(1시간 영상 약 4원)이 이 모델 기준이에요.
// 바꾸려면 .env 파일의 SUMMARY_MODEL 값을 수정하세요.
const MODEL = process.env.SUMMARY_MODEL || "claude-haiku-5-5";

export const SummarySchema = z.object({
  oneLine: z.string().describe("영상 전체를 한 문장으로 요약"),
  keyPoints: z.array(z.string()).describe("가장 중요한 핵심 3가지, 각 한 문장"),
  sections: z
    .array(
      z.object({
        start: z.number().describe("이 구간이 시작하는 시각(초). 대본에 나온 시각 중 하나"),
        title: z.string().describe("구간 제목, 15자 안팎"),
        summary: z.string().describe("구간 내용 요약, 1~2문장"),
      }),
    )
    .describe("영상 흐름에 따른 타임스탬프별 요점, 시간 순서"),
});

export type Summary = z.infer<typeof SummarySchema>;

export class SummaryError extends Error {}

function formatTime(sec: number): string {
  const s = Math.floor(sec);
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const ss = String(s % 60).padStart(2, "0");
  return h > 0 ? `${h}:${String(m).padStart(2, "0")}:${ss}` : `${m}:${ss}`;
}

// 자막 조각을 약 30초 단위로 묶어 [초] 표시와 함께 한 줄씩 만듭니다.
function transcriptToText(t: Transcript): string {
  const lines: string[] = [];
  let bucketStart = -1;
  let buf: string[] = [];
  for (const seg of t.segments) {
    if (bucketStart < 0) bucketStart = seg.start;
    buf.push(seg.text);
    if (seg.start - bucketStart >= 30) {
      lines.push(`[${Math.floor(bucketStart)}] ${buf.join(" ")}`);
      bucketStart = -1;
      buf = [];
    }
  }
  if (buf.length) lines.push(`[${Math.floor(bucketStart)}] ${buf.join(" ")}`);
  return lines.join("\n");
}

function sectionCount(lengthSeconds: number): string {
  const minutes = lengthSeconds / 60;
  if (minutes <= 10) return "3~5개";
  if (minutes <= 30) return "5~8개";
  if (minutes <= 90) return "8~12개";
  return "12~15개";
}

const SYSTEM = `당신은 유튜브 영상을 한국어로 정확하게 요약하는 편집자입니다.
- 대본에 실제로 나온 내용만 씁니다. 대본에 없는 사실, 숫자, 의견을 더하지 않습니다.
- 영상이 외국어여도 요약은 자연스러운 한국어로 씁니다.
- 자동 생성 자막의 오타나 잘못 인식된 단어는 문맥에 맞게 바로잡아 이해합니다.
- 인사, 광고, 구독 요청 같은 부분은 요약에서 뺍니다.
- 각 구간의 start는 대본 줄 앞의 [초] 값 중 그 구간이 시작되는 값을 그대로 씁니다.`;

export function hasApiKey(): boolean {
  return Boolean(process.env.ANTHROPIC_API_KEY || process.env.ANTHROPIC_AUTH_TOKEN);
}

function buildUserContent(t: Transcript): string {
  return `영상 제목: ${t.title}
채널: ${t.channel}
길이: ${formatTime(t.lengthSeconds)}
자막 언어: ${t.language}${t.isAutoGenerated ? " (자동 생성)" : ""}

타임스탬프별 요점은 ${sectionCount(t.lengthSeconds)}로 나눠 주세요.

<transcript>
${transcriptToText(t)}
</transcript>`;
}

// API 키 없이 테스트할 때 claude.ai 채팅에 그대로 붙여 넣을 수 있는 요청문.
export function buildManualPrompt(t: Transcript): string {
  return `${SYSTEM}

아래 영상을 요약해 주세요. 형식:
1. 한 줄 요약
2. 핵심 3가지
3. 타임스탬프별 요점 (시각은 대본의 [초] 값을 분:초로 바꿔서)

${buildUserContent(t)}`;
}

export async function summarize(t: Transcript): Promise<Summary> {
  const client = new Anthropic();
  const userContent = buildUserContent(t);

  const response = await client.messages.parse({
    model: MODEL,
    max_tokens: 16000,
    system: SYSTEM,
    messages: [{ role: "user", content: userContent }],
    output_config: { format: zodOutputFormat(SummarySchema) },
  });

  if (response.stop_reason === "refusal") {
    throw new SummaryError("AI가 이 영상의 요약을 거절했어요.");
  }
  if (response.stop_reason === "max_tokens" || !response.parsed_output) {
    throw new SummaryError("요약을 끝까지 만들지 못했어요. 다시 시도해 주세요.");
  }
  const summary = response.parsed_output;
  summary.sections.sort((a, b) => a.start - b.start);
  return summary;
}

