// Gemini로 유튜브 영상을 직접 보고 요약합니다.
// Gemini는 공개 유튜브 링크를 그대로 받아서 영상과 음성을 분석하기 때문에 자막을 따로 가져올 필요가 없어요.
// 무료 등급은 하루 유튜브 영상 8시간까지예요 (2026년 10월 기준, 미리보기 기능이라 바뀔 수 있음).
import { SummaryError, SummarySchema, type Summary } from "./summarize";
import { TranscriptError, fetchOEmbed, parseVideoId } from "./youtube";

const MODEL = process.env.GEMINI_MODEL || "gemini-3.8-flash";
const API = "https://generativelanguage.googleapis.com/v1beta/models";

export function hasGeminiKey(): boolean {
  return Boolean(process.env.GEMINI_API_KEY);
}

export type GeminiResult = {
  video: {
    id: string;
    title: string;
    channel: string;
    lengthSeconds: number;
    language: string;
    isAutoGenerated: boolean;
  };
  summary: Summary;
};

const PROMPT = `이 유튜브 영상을 보고 한국어로 요약해 주세요.
- 영상에 실제로 나온 내용만 씁니다. 영상에 없는 사실, 숫자, 의견을 더하지 않습니다.
- 영상이 외국어여도 요약은 자연스러운 한국어로 씁니다.
- 인사, 광고, 구독 요청 같은 부분은 빼요.
- lengthSeconds: 영상 전체 길이(초)
- oneLine: 영상 전체를 한 문장으로
- keyPoints: 가장 중요한 핵심 3가지, 각 한 문장
- sections: 영상 흐름에 따른 타임스탬프별 요점. start는 그 구간이 시작하는 시각(초), title은 15자 안팎, summary는 1~2문장. 10분 이하면 3~5개, 30분 이하면 5~8개, 그보다 길면 8~15개.`;

const RESPONSE_SCHEMA = {
  type: "OBJECT",
  properties: {
    lengthSeconds: { type: "NUMBER" },
    oneLine: { type: "STRING" },
    keyPoints: { type: "ARRAY", items: { type: "STRING" } },
    sections: {
      type: "ARRAY",
      items: {
        type: "OBJECT",
        properties: {
          start: { type: "NUMBER" },
          title: { type: "STRING" },
          summary: { type: "STRING" },
        },
        required: ["start", "title", "summary"],
      },
    },
  },
  required: ["lengthSeconds", "oneLine", "keyPoints", "sections"],
};

export async function summarizeWithGemini(input: string): Promise<GeminiResult> {
  const videoId = parseVideoId(input);
  if (!videoId) throw new TranscriptError("INVALID_URL", "유튜브 영상 링크를 확인해 주세요.");
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) throw new SummaryError("GEMINI_API_KEY가 설정되지 않았어요.");

  let res: Response;
  try {
    res = await fetch(`${API}/${MODEL}:generateContent`, {
      method: "POST",
      headers: { "Content-Type": "application/json", "x-goog-api-key": apiKey },
      body: JSON.stringify({
        contents: [
          {
            parts: [
              { file_data: { file_uri: `https://www.youtube.com/watch?v=${videoId}` } },
              { text: PROMPT },
            ],
          },
        ],
        generationConfig: {
          response_mime_type: "application/json",
          response_schema: RESPONSE_SCHEMA,
        },
      }),
    });
  } catch (e) {
    throw new SummaryError(`Gemini에 연결하지 못했어요: ${(e as Error).message}`);
  }

  const body = await res.json().catch(() => ({}));
  if (!res.ok) {
    const msg = body?.error?.message ?? "";
    if (res.status === 429) throw new SummaryError("Gemini 무료 사용 한도를 넘었어요. 내일 다시 시도해 주세요.");
    if (res.status === 400 && /api key/i.test(msg)) throw new SummaryError("Gemini API 키가 잘못됐어요.");
    throw new SummaryError(`Gemini 오류 (${res.status}): ${msg}`);
  }

  const candidate = body.candidates?.[0];
  const text: string = (candidate?.content?.parts ?? []).map((p: { text?: string }) => p.text ?? "").join("");
  if (!text) {
    throw new SummaryError(
      `Gemini가 요약을 돌려주지 않았어요 (${candidate?.finishReason ?? body.promptFeedback?.blockReason ?? "응답 없음"}).`,
    );
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch {
    throw new SummaryError("Gemini 응답 형식을 읽지 못했어요. 다시 시도해 주세요.");
  }
  const lengthSeconds = Number((parsed as { lengthSeconds?: number }).lengthSeconds ?? 0);
  const check = SummarySchema.safeParse(parsed);
  if (!check.success) throw new SummaryError("Gemini 응답에 빠진 항목이 있어요. 다시 시도해 주세요.");
  const summary = check.data;
  summary.sections.sort((a, b) => a.start - b.start);

  const meta = await fetchOEmbed(videoId);
  return {
    video: {
      id: videoId,
      title: meta.title,
      channel: meta.channel,
      lengthSeconds: Math.round(lengthSeconds),
      language: "",
      isAutoGenerated: false,
    },
    summary,
  };
}
