// GitHub Pages용 화면. 워크플로우가 만든 results/*.json을 읽어서 보여줍니다.
const REPO = "MooYooAI/longshots";
const RUN_URL = `https://github.com/${REPO}/actions/workflows/summarize.yml`;
const app = document.getElementById("app");

const esc = (s) =>
  String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);

function formatTime(sec) {
  const s = Math.floor(sec);
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const ss = String(s % 60).padStart(2, "0");
  return h > 0 ? `${h}:${String(m).padStart(2, "0")}:${ss}` : `${m}:${ss}`;
}

const STATUS = {
  summarized: ["요약 완료", ""],
  "transcript-only": ["자막만", ""],
  error: ["실패", "error"],
};

async function getJson(path) {
  const res = await fetch(`${path}?t=${Date.now()}`);
  if (!res.ok) throw new Error(`${path} ${res.status}`);
  return res.json();
}

async function renderHome() {
  let items = [];
  try {
    items = await getJson("results/index.json");
  } catch {}
  app.innerHTML = `
    <header class="hero">
      <h1>긴 유튜브, 핵심만</h1>
      <p>GitHub 워크플로우로 영상을 요약하고, 결과를 여기서 확인해요.</p>
    </header>
    <div class="run-box">
      <h3>새 영상 요약하기</h3>
      <ol>
        <li>아래 버튼을 눌러 GitHub 실행 페이지로 가요.</li>
        <li>오른쪽의 <strong>Run workflow</strong>를 누르고 유튜브 링크를 붙여 넣은 뒤 초록색 <strong>Run workflow</strong>를 눌러요.</li>
        <li>1~2분 뒤 이 페이지를 새로고침하면 목록에 나타나요.</li>
      </ol>
      <a class="button" href="${RUN_URL}" target="_blank" rel="noreferrer">요약 실행하러 가기</a>
    </div>
    <h2 class="section">요약 기록</h2>
    ${
      items.length
        ? `<ul class="list">${items
            .map((it) => {
              const [label, cls] = STATUS[it.status] ?? ["", ""];
              return `<li><a href="#${esc(it.id)}"><span>${esc(it.title)}<br><small>${it.channel ? esc(it.channel) + " · " : ""}${new Date(it.createdAt).toLocaleString("ko-KR")}</small></span><span class="badge ${cls}">${label}</span></a></li>`;
            })
            .join("")}</ul>`
        : `<p class="hint">아직 요약한 영상이 없어요.</p>`
    }`;
}

async function renderDetail(id) {
  let r;
  try {
    r = await getJson(`results/${encodeURIComponent(id)}.json`);
  } catch {
    app.innerHTML = `<a class="back" href="#">← 목록</a><p class="error">결과를 찾지 못했어요. 배포가 끝나지 않았다면 잠시 후 새로고침해 주세요.</p>`;
    return;
  }
  const back = `<a class="back" href="#">← 목록</a>`;
  if (r.status === "error") {
    app.innerHTML = `${back}<div class="card"><h3>실패 (${esc(r.error.code)})</h3><p class="error">${esc(r.error.message)}</p><p>${esc(r.url)}</p></div>`;
    return;
  }
  const v = r.video;
  let body = "";
  if (r.summary) {
    const s = r.summary;
    body = `
      <div class="card">
        <div class="card-head"><h3>한 줄 요약</h3><button class="ghost" id="copy">전체 복사</button></div>
        <p class="one-line">${esc(s.oneLine)}</p>
        <h3>핵심 3가지</h3>
        <ol class="points">${s.keyPoints.map((p) => `<li>${esc(p)}</li>`).join("")}</ol>
      </div>
      <div class="card">
        <h3>타임라인</h3>
        <ul class="timeline">${s.sections
          .map(
            (x) => `<li><button class="time" data-start="${x.start}">${formatTime(x.start)}</button><div><strong>${esc(x.title)}</strong><p>${esc(x.summary)}</p></div></li>`,
          )
          .join("")}</ul>
      </div>`;
  } else {
    body = `
      <div class="card">
        <div class="card-head"><h3>API 키 없이 테스트 중</h3><button class="ghost" id="copy">요청문 복사</button></div>
        <p>자막 ${r.segmentCount}조각을 가져왔어요. <strong>요청문 복사</strong>를 누르고
        <a href="https://claude.ai/new" target="_blank" rel="noreferrer">claude.ai</a>에 붙여 넣으면 요약을 볼 수 있어요.</p>
        <textarea class="prompt" readonly rows="8">${esc(r.manualPrompt)}</textarea>
      </div>`;
  }
  app.innerHTML = `
    ${back}
    <section class="result">
      <div class="player"><iframe id="player" src="https://www.youtube.com/embed/${esc(v.id)}" title="${esc(v.title)}" allow="autoplay; encrypted-media; picture-in-picture" allowfullscreen></iframe></div>
      <div class="meta"><h2>${esc(v.title)}</h2><p>${esc(v.channel)}${v.lengthSeconds ? " · " + formatTime(v.lengthSeconds) : ""}${v.isAutoGenerated ? " · 자동 생성 자막 기준" : ""}</p></div>
      ${body}
      <p class="source">원본: <a href="https://www.youtube.com/watch?v=${esc(v.id)}" target="_blank" rel="noreferrer">${esc(v.channel)} 채널의 영상</a>. 요약은 AI가 만들었으니 중요한 내용은 원본에서 확인해 주세요.</p>
    </section>`;

  app.querySelectorAll("button.time").forEach((b) =>
    b.addEventListener("click", () => {
      document.getElementById("player").src = `https://www.youtube.com/embed/${v.id}?start=${Math.floor(b.dataset.start)}&autoplay=1`;
    }),
  );
  const copyBtn = document.getElementById("copy");
  copyBtn?.addEventListener("click", async () => {
    const text = r.summary
      ? [
          `${v.title} (${v.channel})`,
          `https://youtu.be/${v.id}`,
          "",
          r.summary.oneLine,
          "",
          "핵심",
          ...r.summary.keyPoints.map((p) => `- ${p}`),
          "",
          "타임라인",
          ...r.summary.sections.map((x) => `${formatTime(x.start)} ${x.title}: ${x.summary}`),
        ].join("\n")
      : r.manualPrompt;
    await navigator.clipboard.writeText(text);
    copyBtn.textContent = "복사됨";
  });
}

function route() {
  const id = decodeURIComponent(location.hash.slice(1));
  window.scrollTo(0, 0);
  id ? renderDetail(id) : renderHome();
}
window.addEventListener("hashchange", route);
route();
