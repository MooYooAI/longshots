"use client";

import { useState } from "react";

type Section = { start: number; title: string; summary: string };
type Result = {
  video: {
    id: string;
    title: string;
    channel: string;
    lengthSeconds: number;
    language: string;
    isAutoGenerated: boolean;
  };
  summary: { oneLine: string; keyPoints: string[]; sections: Section[] };
};

function formatTime(sec: number): string {
  const s = Math.floor(sec);
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const ss = String(s % 60).padStart(2, "0");
  return h > 0 ? `${h}:${String(m).padStart(2, "0")}:${ss}` : `${m}:${ss}`;
}

function toPlainText(r: Result): string {
  const { video, summary } = r;
  return [
    `${video.title} (${video.channel})`,
    `https://youtu.be/${video.id}`,
    "",
    summary.oneLine,
    "",
    "핵심",
    ...summary.keyPoints.map((p) => `- ${p}`),
    "",
    "타임라인",
    ...summary.sections.map((s) => `${formatTime(s.start)} ${s.title}: ${s.summary}`),
  ].join("\n");
}

export default function Home() {
  const [url, setUrl] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<Result | null>(null);
  const [seek, setSeek] = useState(0);
  const [copied, setCopied] = useState(false);

  async function onSubmit(e: React.FormEvent) {
    e.preventDefault();
    if (!url.trim() || loading) return;
    setLoading(true);
    setError(null);
    setResult(null);
    setSeek(0);
    try {
      const res = await fetch("/api/summarize", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ url }),
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error ?? "요약에 실패했어요.");
      setResult(data);
    } catch (err) {
      setError((err as Error).message);
    } finally {
      setLoading(false);
    }
  }

  async function copy() {
    if (!result) return;
    await navigator.clipboard.writeText(toPlainText(result));
    setCopied(true);
    setTimeout(() => setCopied(false), 1500);
  }

  return (
    <main className="container">
      <header className="hero">
        <h1>긴 유튜브, 핵심만</h1>
        <p>링크를 붙여 넣으면 AI가 세 줄 요약과 구간별 요점을 만들어 드려요.</p>
      </header>

      <form className="search" onSubmit={onSubmit}>
        <input
          type="url"
          inputMode="url"
          placeholder="https://www.youtube.com/watch?v=..."
          value={url}
          onChange={(e) => setUrl(e.target.value)}
          aria-label="유튜브 링크"
        />
        <button type="submit" disabled={loading || !url.trim()}>
          {loading ? "요약 중..." : "요약하기"}
        </button>
      </form>

      {loading && <p className="hint">영상 길이에 따라 10~30초 정도 걸려요.</p>}
      {error && <p className="error">{error}</p>}

      {result && (
        <section className="result">
          <div className="player">
            <iframe
              key={seek}
              src={`https://www.youtube.com/embed/${result.video.id}?start=${Math.floor(seek)}${seek ? "&autoplay=1" : ""}`}
              title={result.video.title}
              allow="autoplay; encrypted-media; picture-in-picture"
              allowFullScreen
            />
          </div>

          <div className="meta">
            <h2>{result.video.title}</h2>
            <p>
              {result.video.channel} · {formatTime(result.video.lengthSeconds)}
              {result.video.isAutoGenerated && " · 자동 생성 자막 기준"}
            </p>
          </div>

          <div className="card">
            <div className="card-head">
              <h3>한 줄 요약</h3>
              <button className="ghost" onClick={copy}>
                {copied ? "복사됨" : "전체 복사"}
              </button>
            </div>
            <p className="one-line">{result.summary.oneLine}</p>
            <h3>핵심 3가지</h3>
            <ol className="points">
              {result.summary.keyPoints.map((p, i) => (
                <li key={i}>{p}</li>
              ))}
            </ol>
          </div>

          <div className="card">
            <h3>타임라인</h3>
            <ul className="timeline">
              {result.summary.sections.map((s, i) => (
                <li key={i}>
                  <button className="time" onClick={() => setSeek(s.start)}>
                    {formatTime(s.start)}
                  </button>
                  <div>
                    <strong>{s.title}</strong>
                    <p>{s.summary}</p>
                  </div>
                </li>
              ))}
            </ul>
          </div>

          <p className="source">
            원본:{" "}
            <a href={`https://www.youtube.com/watch?v=${result.video.id}`} target="_blank" rel="noreferrer">
              {result.video.channel} 채널의 영상
            </a>
            . 요약은 AI가 만들었으니 중요한 내용은 원본에서 확인해 주세요.
          </p>
        </section>
      )}
    </main>
  );
}
