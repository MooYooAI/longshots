import Anthropic from "@anthropic-ai/sdk";
import { NextResponse } from "next/server";
import { SummaryError, buildManualPrompt, hasApiKey, summarize } from "@/lib/summarize";
import { TranscriptError, fetchTranscript } from "@/lib/youtube";

export const runtime = "nodejs";
export const maxDuration = 120;

function fail(message: string, status: number, code?: string) {
  return NextResponse.json({ error: message, code }, { status });
}

export async function POST(req: Request) {
  let url: unknown;
  try {
    ({ url } = await req.json());
  } catch {
    return fail("요청 형식이 올바르지 않아요.", 400);
  }
  if (typeof url !== "string" || !url.trim()) {
    return fail("유튜브 링크를 입력해 주세요.", 400);
  }

  try {
    const transcript = await fetchTranscript(url);
    const video = {
      id: transcript.videoId,
      title: transcript.title,
      channel: transcript.channel,
      lengthSeconds: transcript.lengthSeconds,
      language: transcript.language,
      isAutoGenerated: transcript.isAutoGenerated,
    };
    // API 키가 없으면 자막까지만 가져오고, 직접 붙여 넣을 요청문을 돌려줍니다.
    if (!hasApiKey()) {
      return NextResponse.json({
        video,
        summary: null,
        manualPrompt: buildManualPrompt(transcript),
        segmentCount: transcript.segments.length,
      });
    }
    const summary = await summarize(transcript);
    return NextResponse.json({ video, summary });
  } catch (e) {
    if (e instanceof TranscriptError) {
      const status = e.code === "INVALID_URL" ? 400 : e.code === "BLOCKED" ? 503 : 422;
      return fail(e.message, status, e.code);
    }
    if (e instanceof SummaryError) return fail(e.message, 502);
    if (e instanceof Anthropic.AuthenticationError) {
      return fail("AI API 키가 없거나 잘못됐어요. .env.local의 ANTHROPIC_API_KEY를 확인해 주세요.", 500, "NO_API_KEY");
    }
    if (e instanceof Anthropic.RateLimitError) {
      return fail("요청이 많아요. 잠시 후 다시 시도해 주세요.", 429);
    }
    if (e instanceof Anthropic.APIError) {
      return fail(`AI 요약 중 오류가 났어요 (${e.status ?? "연결 실패"}).`, 502);
    }
    if (e instanceof Error && /api key|apiKey|authToken/i.test(e.message)) {
      return fail("AI API 키가 설정되지 않았어요. .env.local에 ANTHROPIC_API_KEY를 넣어 주세요.", 500, "NO_API_KEY");
    }
    console.error(e);
    return fail("알 수 없는 오류가 났어요.", 500);
  }
}
