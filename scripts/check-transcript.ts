// 이 컴퓨터(또는 서버)에서 유튜브 자막을 가져올 수 있는지 확인합니다.
// 사용법: npm run check:transcript -- "https://www.youtube.com/watch?v=..."
import { fetchTranscript } from "../lib/youtube";

const url = process.argv[2] ?? "https://www.youtube.com/watch?v=jNQXAC9IVRw";
fetchTranscript(url)
  .then((t) => {
    console.log(`성공: ${t.title} (${t.channel})`);
    console.log(`자막 언어 ${t.language}${t.isAutoGenerated ? " (자동)" : ""}, ${t.segments.length}조각`);
    console.log(t.segments.slice(0, 5).map((s) => `[${s.start}] ${s.text}`).join("\n"));
  })
  .catch((e) => {
    console.error(`실패 (${e.code ?? "ERROR"}): ${e.message}`);
    process.exit(1);
  });
