// GitHub 워크플로우에서 실행하는 요약 스크립트.
// 결과를 site/results/<id>.json 으로 저장하고 site/results/index.json 목록을 갱신합니다.
// 사용법: npx tsx scripts/summarize-cli.ts "https://www.youtube.com/watch?v=..."
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { buildManualPrompt, formatTime, hasApiKey, summarize, type Summary } from "../lib/summarize";
import { hasGeminiKey, summarizeWithGemini } from "../lib/gemini";
import { fetchTranscript, parseVideoId } from "../lib/youtube";

const RESULTS_DIR = "site/results";
const INDEX_FILE = `${RESULTS_DIR}/index.json`;

type IndexEntry = {
  id: string;
  title: string;
  channel: string;
  status: "summarized" | "transcript-only" | "error";
  createdAt: string;
};

type Result = {
  id: string;
  url: string;
  createdAt: string;
  status: IndexEntry["status"];
  video?: {
    id: string;
    title: string;
    channel: string;
    lengthSeconds: number;
    language: string;
    isAutoGenerated: boolean;
  };
  summary?: Summary;
  manualPrompt?: string;
  segmentCount?: number;
  error?: { code: string; message: string };
};

function writeStepSummary(markdown: string) {
  const file = process.env.GITHUB_STEP_SUMMARY;
  if (file) appendFileSync(file, markdown + "\n");
  console.log(markdown);
}

async function main() {
  const url = (process.argv[2] ?? "").trim();
  if (!url) {
    console.error("유튜브 링크를 넣어 주세요.");
    process.exit(1);
  }
  const createdAt = new Date().toISOString();
  const id = `${parseVideoId(url) ?? "invalid"}-${createdAt.slice(0, 19).replace(/[-:T]/g, "")}`;
  const result: Result = { id, url, createdAt, status: "error" };

  try {
    // GEMINI_API_KEY가 있으면 Gemini가 영상을 직접 보고 요약해요 (자막 불필요).
    if (hasGeminiKey()) {
      const g = await summarizeWithGemini(url);
      result.video = g.video;
      result.summary = g.summary;
      result.status = "summarized";
      return finish(result, url, id, createdAt);
    }
    const t = await fetchTranscript(url);
    result.video = {
      id: t.videoId,
      title: t.title,
      channel: t.channel,
      lengthSeconds: t.lengthSeconds,
      language: t.language,
      isAutoGenerated: t.isAutoGenerated,
    };
    result.segmentCount = t.segments.length;
    if (hasApiKey()) {
      result.summary = await summarize(t);
      result.status = "summarized";
    } else {
      result.manualPrompt = buildManualPrompt(t);
      result.status = "transcript-only";
    }
  } catch (e) {
    const err = e as Error & { code?: string };
    result.error = { code: err.code ?? "ERROR", message: err.message };
  }
  finish(result, url, id, createdAt);
}

function finish(result: Result, url: string, id: string, createdAt: string) {
  mkdirSync(RESULTS_DIR, { recursive: true });
  writeFileSync(`${RESULTS_DIR}/${id}.json`, JSON.stringify(result, null, 2) + "\n");

  const index: IndexEntry[] = existsSync(INDEX_FILE)
    ? JSON.parse(readFileSync(INDEX_FILE, "utf8"))
    : [];
  index.unshift({
    id,
    title: result.video?.title || url,
    channel: result.video?.channel ?? "",
    status: result.status,
    createdAt,
  });
  writeFileSync(INDEX_FILE, JSON.stringify(index, null, 2) + "\n");

  const pageUrl = process.env.PAGES_URL ? `${process.env.PAGES_URL}#${id}` : "";
  if (result.status === "error") {
    writeStepSummary(`## 실패: ${result.error!.code}\n\n${result.error!.message}\n\n링크: ${url}`);
    return;
  }
  const v = result.video!;
  const lines = [`## ${v.title}`, `${v.channel} · ${formatTime(v.lengthSeconds)}${result.segmentCount ? ` · 자막 ${result.segmentCount}조각` : ""}`, ""];
  if (result.summary) {
    lines.push(`**${result.summary.oneLine}**`, "");
    lines.push(...result.summary.keyPoints.map((p) => `- ${p}`), "");
    lines.push(...result.summary.sections.map((s) => `- \`${formatTime(s.start)}\` **${s.title}** ${s.summary}`));
  } else {
    lines.push("자막을 가져왔어요. API 키가 없어서 요약 요청문만 만들었어요.");
  }
  if (pageUrl) lines.push("", `사이트에서 보기: ${pageUrl}`);
  writeStepSummary(lines.join("\n"));
}

main();
